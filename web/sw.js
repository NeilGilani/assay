// FIELD's service worker: install once, then run with no network at all.
//
// Three jobs:
//
// 1. Precache everything - app, inference runtime, the 40 MB model - on first
//    visit, so the next launch works in airplane mode. The page waits for this
//    to finish and then loads the model *from this cache*, so the model is
//    downloaded exactly once.
// 2. Refuse to talk to anyone but this origin. The page's CSP already blocks
//    other destinations; this is the second lock on the same door.
// 3. Count what actually went over the network, and tell the page. The "0
//    sent" on screen is this count, not a slogan.

// <precache> generated by scripts/build-manifest.mjs - do not edit by hand
const VERSION = "4b673e5c3865";
const PRECACHE_BYTES = 66487084;
const PRECACHE = [
  "./",
  "icons/icon.svg",
  "manifest.webmanifest",
  "js/perception/detector.js",
  "js/ui/simview.js",
  "js/ui/overlay.js",
  "models/detector.json",
  "js/sensors.js",
  "js/perception/yolo.js",
  "fonts/Geist-OFL.txt",
  "js/perception/worker.js",
  "js/geometry.js",
  "js/scenario.js",
  "icons/icon-192.png",
  "js/ontology.js",
  "index.html",
  "js/ui/map.js",
  "app.css",
  "js/model.js",
  "js/ask.js",
  "js/reason.js",
  "icons/icon-512.png",
  "js/app.js",
  "vendor/ort/ort-wasm-simd-threaded.asyncify.mjs",
  "vendor/ort/ort.webgpu.min.mjs",
  "fonts/Geist-Variable.woff2",
  "vendor/ort/ort-wasm-simd-threaded.asyncify.wasm",
  "models/detector.onnx"
];
// </precache>

const CACHE = `field-${VERSION}`;

const CSP =
  "default-src 'self'; script-src 'self' 'wasm-unsafe-eval'; worker-src 'self' blob:; connect-src 'self' blob: data:; " +
  "img-src 'self' blob: data:; media-src 'self' blob:; style-src 'self' 'unsafe-inline'; font-src 'self'; object-src 'none'; base-uri 'none'; form-action 'none'";

const HEADERS = {
  "Cross-Origin-Opener-Policy": "same-origin",
  "Cross-Origin-Embedder-Policy": "require-corp",
  "Cross-Origin-Resource-Policy": "same-origin",
  "Content-Security-Policy": CSP,
};

let network = { requests: 0, bytes: 0, refused: 0, last: null };

async function broadcast(msg) {
  for (const c of await self.clients.matchAll({ includeUncontrolled: true })) c.postMessage(msg);
}

function noteNetwork(url, res) {
  network.requests += 1;
  network.bytes += Number(res.headers.get("content-length")) || 0;
  network.last = new URL(url).pathname;
  broadcast({ type: "network", ...network });
}

self.addEventListener("install", (event) => {
  event.waitUntil(
    (async () => {
      const cache = await caches.open(CACHE);
      let done = 0;
      let bytes = 0;
      // small files first so the app shell is usable early; big ones last
      for (const path of PRECACHE) {
        const req = new Request(path, { cache: "reload" });
        let res = await cache.match(req);
        if (!res) {
          res = await fetch(req);
          if (!res.ok) throw new Error(`precache ${path}: HTTP ${res.status}`);
          noteNetwork(req.url, res);
          await cache.put(req, res.clone());
        }
        bytes += Number(res.headers.get("content-length")) || 0;
        done += 1;
        broadcast({ type: "precache", done, total: PRECACHE.length, bytes, totalBytes: PRECACHE_BYTES, version: VERSION });
      }
      await self.skipWaiting();
    })(),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      for (const key of await caches.keys()) if (key.startsWith("field-") && key !== CACHE) await caches.delete(key);
      await self.clients.claim();
      broadcast({ type: "activated", version: VERSION });
    })(),
  );
});

function withHeaders(res) {
  const headers = new Headers(res.headers);
  for (const [k, v] of Object.entries(HEADERS)) headers.set(k, v);
  return new Response(res.body, { status: res.status, statusText: res.statusText, headers });
}

self.addEventListener("fetch", (event) => {
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) {
    // Nothing in FIELD should ever ask for this. If something does, it is
    // refused here and the page is told, so it shows up as a counted attempt.
    network.refused += 1;
    broadcast({ type: "network", ...network, refusedUrl: url.origin });
    event.respondWith(Response.error());
    return;
  }
  if (event.request.method !== "GET") return;
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE);
      const key = event.request.mode === "navigate" ? new Request("./") : event.request;
      const hit = await cache.match(key, { ignoreSearch: true });
      if (hit) return withHeaders(hit);
      const res = await fetch(event.request);
      noteNetwork(event.request.url, res);
      return withHeaders(res);
    })(),
  );
});

self.addEventListener("message", async (event) => {
  if (event.data?.type !== "status") return;
  const cache = await caches.open(CACHE);
  const keys = await cache.keys();
  event.source?.postMessage({
    type: "status",
    version: VERSION,
    cached: keys.length,
    total: PRECACHE.length,
    totalBytes: PRECACHE_BYTES,
    complete: keys.length >= PRECACHE.length,
    network,
  });
});
