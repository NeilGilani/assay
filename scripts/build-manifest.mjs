// Write the offline precache list into web/sw.js.
//
// The service worker has to know every file the app needs before the network
// goes away - including the 40 MB model and the inference runtime - and its
// cache must change name whenever any of them change, or a phone keeps
// running yesterday's model. So the list and a content hash of everything in
// it are generated here and spliced into sw.js between the markers.

import { createHash } from "node:crypto";
import { readFileSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const web = fileURLToPath(new URL("../web/", import.meta.url));
const SKIP = [/\.map$/, /(^|\/)README\.md$/, /^sw\.js$/, /^_headers$/, /(^|\/)\./];

function walk(dir) {
  const out = [];
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) out.push(...walk(p));
    else out.push(relative(web, p).split(sep).join("/"));
  }
  return out;
}

// smallest first: the app shell is cached in a second, the model last
const files = walk(web)
  .filter((f) => !SKIP.some((re) => re.test(f)))
  .sort((a, b) => statSync(join(web, a)).size - statSync(join(web, b)).size || a.localeCompare(b));
const hash = createHash("sha256");
let bytes = 0;
for (const f of files) {
  const buf = readFileSync(join(web, f));
  bytes += buf.length;
  hash.update(f).update("\0").update(buf);
}
const version = hash.digest("hex").slice(0, 12);

const swPath = join(web, "sw.js");
const sw = readFileSync(swPath, "utf8");
const block = `// <precache> generated by scripts/build-manifest.mjs - do not edit by hand
const VERSION = ${JSON.stringify(version)};
const PRECACHE_BYTES = ${bytes};
const PRECACHE = ${JSON.stringify(["./", ...files], null, 2)};
// </precache>`;
const next = sw.replace(/\/\/ <precache>[\s\S]*?\/\/ <\/precache>/, block);
if (next === sw && !sw.includes(block)) {
  console.error("sw.js has no <precache> markers");
  process.exit(1);
}
if (next !== sw) writeFileSync(swPath, next);
console.log(`precache ${files.length} files, ${(bytes / 1e6).toFixed(1)} MB, version ${version}`);
